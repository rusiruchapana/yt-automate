from __future__ import annotations

import math
import struct
import wave
from pathlib import Path

from PIL import Image, ImageDraw

from .domain import create_jobs
from .media import register_file

SOURCE = "https://bts.ibighit.com/eng/discography/detail/map_of_the_soul-7.html"


def seed(store):
    existing = store.one("SELECT id FROM jobs WHERE is_demo=1 ORDER BY created_at LIMIT 1")
    if existing:
        return existing["id"]
    for index, color in enumerate(((117, 67, 219), (44, 123, 163), (157, 67, 138))):
        title = f"Original abstract demo {index + 1}"
        if store.one("SELECT id FROM assets WHERE title=?", (title,)):
            continue
        path = store.root / "work" / f"demo-{index}.png"
        im = Image.new("RGB", (720, 1280))
        draw = ImageDraw.Draw(im)
        for y in range(1280):
            f = y / 1280
            draw.line((0, y, 720, y), fill=tuple(int(c * (0.18 + 0.5 * (1-f))) for c in color))
        for i in range(7):
            x = 50 + i * 100
            y = 430 + int(65 * math.sin(i + index))
            draw.ellipse((x-27, y-27, x+27, y+27), fill=tuple(min(255, c+55) for c in color))
        draw.arc((-180, 100, 900, 1190), start=210, end=340, fill=(209, 190, 252), width=3)
        draw.arc((0, 220, 720, 1040), start=170, end=310, fill=(102, 83, 156), width=2)
        im.save(path)
        register_file(store, path, title, "visual", rights_notes="Original abstract artwork. CC0. No official BTS artwork or likenesses.", enabled=True)
    if not store.one("SELECT id FROM assets WHERE title='Original demo tone loop'"):
        path = store.root / "work" / "demo-loop.wav"
        rate = 22050
        frequencies = [261.63, 329.63, 392.00, 523.25, 392.00, 329.63, 293.66, 349.23]
        with wave.open(str(path), "wb") as f:
            f.setnchannels(1)
            f.setsampwidth(2)
            f.setframerate(rate)
            for n in range(rate * 12):
                t = n / rate
                freq = frequencies[int(t * 2) % len(frequencies)]
                beat = (t * 2) % 1
                envelope = min(1, beat * 20) * math.exp(-4 * beat)
                value = int(6500 * envelope * (math.sin(2*math.pi*freq*t) + .18*math.sin(2*math.pi*freq*2*t)))
                f.writeframesraw(struct.pack("<h", value))
        register_file(store, path, "Original demo tone loop", "music", "calm",
                      rights_notes="Original procedural tone loop generated by this starter. CC0; not a BTS recording.", enabled=True)
    ids = create_jobs(store, [{
        "title": "BTS fan quiz - local preview demo",
        "format": "quiz", "mood": "calm", "source_url": SOURCE,
        "scenes": ["A quick ARMY quiz: how many members are in BTS?", "Choose your answer: five, six, or seven?", "Seven members. Replace this demo with your own original quiz and visuals."],
        "seconds_per_scene": 4, "audience": "general", "is_demo": True,
        "description": "Technical preview only. Original abstract visuals and original tone loop."
    }])
    return ids[0]
